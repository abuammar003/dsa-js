// 1. Write a Function to check if a number is Even or Odd.
function checkEvenOdd() {
    for(let i = 1; i <= 10; i++) {
        if(i %2 === 0) {
            console.log("The Number is Even:", i);
        } else if (i %2 === 1) {
            console.log("The Number is Odd:", i)
        }
    }
}
checkEvenOdd();



